import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import type { AzdoSettings } from "@shared/types";
import {
  AzdoClient,
  buildAzdoFieldOps,
  buildAzdoTags,
  buildFeatureWiql,
  LEGACY_PARENT_COMMENT,
  missingField,
  PARENT_COMMENT,
  PARENT_REL,
  PREDECESSOR_REL,
  previewAzdo,
  storyPointsField,
  testAzdo,
  type JsonPatchOp,
} from "./azdo";
import { httpDefaults, RemoteServiceError } from "./http";
import { mockFetch, sampleContent, silentLog } from "./testUtils";

const settings: AzdoSettings = {
  orgUrl: "https://dev.azure.com/acme/",
  project: "Acme Portal",
  pat: "pat123",
  workItemType: "User Story",
  parentWorkItemType: "Feature",
  areaPath: "Acme Portal\\Web",
  iterationPath: "",
  tags: ["Imported", "coherence"],
};
const options = {
  createFeatureParents: true,
  linkDependencies: true,
  updateExisting: true,
  includeStoryPoints: true,
};

beforeEach(() => {
  httpDefaults.baseDelayMs = 0;
});
afterEach(() => {
  vi.unstubAllGlobals();
  httpDefaults.baseDelayMs = 800;
});

function field(ops: JsonPatchOp[], name: string): unknown {
  return ops.find((o) => o.path === `/fields/${name}`)?.value;
}

describe("Azure DevOps payloads", () => {
  it("builds JSON Patch ops with HTML description and acceptance criteria", () => {
    const ops = buildAzdoFieldOps(sampleContent(), settings, {
      includeStoryPoints: true,
    });
    expect(field(ops, "System.Title")).toBe(
      "[UC-003] Sign in with email and password",
    );
    const description = field(ops, "System.Description") as string;
    expect(description).toContain("<strong>As a</strong> registered user<br>");
    expect(description).toContain(
      "<h3>BR-01 · Email address — Email input</h3>",
    );
    expect(description).toContain("<code>login.email</code>");
    expect(description).not.toContain("SC-01");
    expect(description).toContain(
      "<em>Generated by Coherence — UC-003 rev 2</em>",
    );
    const ac = field(ops, "Microsoft.VSTS.Common.AcceptanceCriteria") as string;
    expect(ac).toContain("<h4>SC-01 · Successful sign-in (happy path)</h4>");
    expect(ac).toContain(
      "<strong>GIVEN</strong> the Login screen is displayed<br>",
    );
    expect(ac).toContain("<strong>AND</strong> the user has an active account");
    expect(ac).toContain(
      "<strong>THEN</strong> the Dashboard screen is displayed",
    );
    expect(field(ops, "System.Tags")).toBe("Coherence; UC-003; Imported");
    expect(field(ops, "System.AreaPath")).toBe("Acme Portal\\Web");
    expect(field(ops, "System.IterationPath")).toBeUndefined();
    expect(field(ops, "Microsoft.VSTS.Scheduling.StoryPoints")).toBe(5);
  });

  it("moves scenarios into the description when the type has no Acceptance Criteria field", () => {
    const ops = buildAzdoFieldOps(sampleContent(), settings, {
      includeStoryPoints: false,
      acceptanceInDescription: true,
    });
    expect(
      field(ops, "Microsoft.VSTS.Common.AcceptanceCriteria"),
    ).toBeUndefined();
    expect(field(ops, "System.Description")).toContain(
      "<h2>Acceptance criteria</h2>",
    );
    expect(field(ops, "Microsoft.VSTS.Scheduling.StoryPoints")).toBeUndefined();
  });

  it("merges tags and picks the story points field per process", () => {
    // An item exported before the rename keeps its old tag.
    expect(buildAzdoTags(settings, "UC-003", "Team X; screenscribe")).toBe(
      "Team X; screenscribe; Coherence; UC-003; Imported",
    );
    expect(storyPointsField("Product Backlog Item")).toBe(
      "Microsoft.VSTS.Scheduling.Effort",
    );
    expect(storyPointsField("Requirement")).toBe(
      "Microsoft.VSTS.Scheduling.Size",
    );
    expect(storyPointsField("User Story")).toBe(
      "Microsoft.VSTS.Scheduling.StoryPoints",
    );
  });

  it("escapes quotes in WIQL", () => {
    expect(buildFeatureWiql("Feature", "Owner's area")).toContain(
      "[System.Title] = 'Owner''s area'",
    );
  });

  it("looks a feature up by the same truncated title that create sends", () => {
    const long = `Orders ${"x".repeat(300)}`;
    const title =
      /\[System\.Title\] = '([^']*)'/.exec(
        buildFeatureWiql("Feature", long),
      )?.[1] ?? "";
    expect(title).toHaveLength(255);
    expect(title.endsWith("…")).toBe(true);
  });

  it("leaves Area and Iteration path alone on update", () => {
    const planned = { ...settings, iterationPath: "Acme Portal\\Backlog" };
    const created = buildAzdoFieldOps(sampleContent(), planned, {
      includeStoryPoints: false,
    });
    expect(field(created, "System.IterationPath")).toBe("Acme Portal\\Backlog");
    const updated = buildAzdoFieldOps(sampleContent(), planned, {
      includeStoryPoints: false,
      update: true,
    });
    expect(field(updated, "System.AreaPath")).toBeUndefined();
    expect(field(updated, "System.IterationPath")).toBeUndefined();
  });

  it("recognises a missing-field error", () => {
    const err = new RemoteServiceError("x", "Azure DevOps", 400, {
      message:
        "TF51535: Cannot find field Microsoft.VSTS.Common.AcceptanceCriteria.",
    });
    expect(missingField(err)).toBe("Microsoft.VSTS.Common.AcceptanceCriteria");
  });

  it("previews HTML description and acceptance criteria", () => {
    const p = previewAzdo(sampleContent(), settings);
    expect(p.bodyFormat).toBe("html");
    expect(p.acceptanceCriteria).toContain("<strong>WHEN</strong>");
    expect(p.fields["System.Tags"]).toBe("Coherence; UC-003; Imported");
  });
});

describe("AzdoClient", () => {
  it("creates a work item with a parent relation and PAT auth", async () => {
    const { calls } = mockFetch([
      [
        /POST .*\/_apis\/wit\/workitems\/\$User%20Story\?api-version=7\.1$/,
        { json: { id: 4711 } },
      ],
    ]);
    const client = new AzdoClient(settings, { log: silentLog });
    const r = await client.upsert({
      content: sampleContent(),
      options,
      parent: { key: "100", url: "x" },
    });
    expect(r).toEqual({
      action: "created",
      ref: {
        key: "4711",
        url: "https://dev.azure.com/acme/Acme%20Portal/_workitems/edit/4711",
      },
    });
    expect(calls[0].url).toBe(
      "https://dev.azure.com/acme/Acme%20Portal/_apis/wit/workitems/$User%20Story?api-version=7.1",
    );
    expect(calls[0].headers["Content-Type"]).toBe(
      "application/json-patch+json",
    );
    expect(calls[0].headers.Authorization).toBe(
      `Basic ${Buffer.from(":pat123").toString("base64")}`,
    );
    const ops = calls[0].body as JsonPatchOp[];
    expect(ops.at(-1)).toEqual({
      op: "add",
      path: "/relations/-",
      value: {
        rel: PARENT_REL,
        url: "https://dev.azure.com/acme/_apis/wit/workItems/100",
        attributes: { comment: "Feature group (Coherence)" },
      },
    });
  });

  // A parent set before the visible rename carries the old relation comment and is still Coherence's own.
  it.each([PARENT_COMMENT, LEGACY_PARENT_COMMENT])(
    "updates an existing item, merging tags and replacing a parent Coherence set (%s)",
    async (comment) => {
      const { calls } = mockFetch([
        [
          /GET .*\/workitems\/4711\?\$expand=relations/,
          {
            json: {
              id: 4711,
              fields: { "System.Tags": "Team X" },
              relations: [
                {
                  rel: "System.LinkTypes.Related",
                  url: "https://dev.azure.com/acme/_apis/wit/workItems/5",
                },
                {
                  rel: PARENT_REL,
                  url: "https://dev.azure.com/acme/_apis/wit/workItems/99",
                  attributes: { comment },
                },
              ],
            },
          },
        ],
        [
          /PATCH .*\/workitems\/4711\?api-version=7\.1$/,
          { json: { id: 4711 } },
        ],
      ]);
      const client = new AzdoClient(settings, { log: silentLog });
      const r = await client.upsert({
        content: sampleContent(),
        options,
        parent: { key: "100", url: "x" },
        existing: {
          system: "azdo",
          key: "4711",
          url: "u",
          revision: 1,
          exportedAt: "x",
        },
      });
      expect(r.action).toBe("updated");
      const ops = calls[1].body as JsonPatchOp[];
      expect(field(ops, "System.Tags")).toBe(
        "Team X; Coherence; UC-003; Imported",
      );
      expect(ops).toContainEqual({ op: "remove", path: "/relations/1" });
      expect(ops.at(-1)?.value).toMatchObject({
        rel: PARENT_REL,
        url: "https://dev.azure.com/acme/_apis/wit/workItems/100",
      });
    },
  );

  it("keeps the team's sprint, estimate and parent when updating", async () => {
    const info = vi.fn();
    const { calls } = mockFetch([
      [
        /GET .*\/workitems\/4711\?\$expand=relations/,
        {
          json: {
            id: 4711,
            fields: {
              "System.Tags": "ScreenScribe; UC-003",
              "System.IterationPath": "Acme Portal\\Sprint 12",
              "Microsoft.VSTS.Scheduling.StoryPoints": 13,
            },
            relations: [
              {
                rel: PARENT_REL,
                url: "https://dev.azure.com/acme/_apis/wit/workItems/77",
                attributes: { isLocked: false, name: "Parent" },
              },
            ],
          },
        },
      ],
      [/PATCH .*\/workitems\/4711\?api-version=7\.1$/, { json: { id: 4711 } }],
    ]);
    const client = new AzdoClient(
      { ...settings, iterationPath: "Acme Portal\\Backlog" },
      { log: { info, warn: vi.fn() } },
    );
    await client.upsert({
      content: sampleContent(),
      options,
      parent: { key: "100", url: "x" },
      existing: {
        system: "azdo",
        key: "4711",
        url: "u",
        revision: 1,
        exportedAt: "x",
      },
    });
    const ops = calls[1].body as JsonPatchOp[];
    expect(field(ops, "System.Title")).toBe(
      "[UC-003] Sign in with email and password",
    );
    expect(field(ops, "System.IterationPath")).toBeUndefined();
    expect(field(ops, "System.AreaPath")).toBeUndefined();
    expect(field(ops, "Microsoft.VSTS.Scheduling.StoryPoints")).toBeUndefined();
    expect(ops.some((o) => o.path.startsWith("/relations"))).toBe(false);
    expect(info).toHaveBeenCalledWith(
      expect.stringContaining("keeps the parent 77"),
    );
  });

  it("fills empty story points and a missing parent on update", async () => {
    const { calls } = mockFetch([
      [
        /GET .*\/workitems\/4711\?\$expand=relations/,
        { json: { id: 4711, fields: { "System.Tags": "" } } },
      ],
      [/PATCH .*\/workitems\/4711\?api-version=7\.1$/, { json: { id: 4711 } }],
    ]);
    const client = new AzdoClient(settings, { log: silentLog });
    await client.upsert({
      content: sampleContent(),
      options,
      parent: { key: "100", url: "x" },
      existing: {
        system: "azdo",
        key: "4711",
        url: "u",
        revision: 1,
        exportedAt: "x",
      },
    });
    const ops = calls[1].body as JsonPatchOp[];
    expect(field(ops, "Microsoft.VSTS.Scheduling.StoryPoints")).toBe(5);
    expect(ops.at(-1)?.value).toMatchObject({
      rel: PARENT_REL,
      attributes: { comment: PARENT_COMMENT },
    });
  });

  it("recreates a deleted work item (404)", async () => {
    const { calls } = mockFetch([
      [
        /GET .*\/workitems\/4711/,
        {
          status: 404,
          json: { message: "TF401232: Work item 4711 does not exist." },
        },
      ],
      [/POST .*workitems\/\$/, { json: { id: 4800 } }],
    ]);
    const client = new AzdoClient(settings, { log: silentLog });
    const r = await client.upsert({
      content: sampleContent(),
      options,
      existing: {
        system: "azdo",
        key: "4711",
        url: "u",
        revision: 1,
        exportedAt: "x",
      },
    });
    expect(r).toMatchObject({ action: "created", ref: { key: "4800" } });
    expect(calls.map((c) => c.method)).toEqual(["GET", "POST"]);
  });

  it("retries without fields the work item type does not have", async () => {
    const warn = vi.fn();
    let n = 0;
    const { calls } = mockFetch([
      [
        /POST/,
        () => {
          n++;
          if (n === 1)
            return {
              status: 400,
              json: {
                message:
                  "TF51535: Cannot find field Microsoft.VSTS.Common.AcceptanceCriteria.",
              },
            };
          if (n === 2)
            return {
              status: 400,
              json: {
                message:
                  "TF51535: Cannot find field Microsoft.VSTS.Scheduling.StoryPoints.",
              },
            };
          return { json: { id: 1 } };
        },
      ],
    ]);
    const client = new AzdoClient(settings, { log: { info: vi.fn(), warn } });
    await client.upsert({ content: sampleContent(), options });
    const ops = calls[2].body as JsonPatchOp[];
    expect(
      field(ops, "Microsoft.VSTS.Common.AcceptanceCriteria"),
    ).toBeUndefined();
    expect(field(ops, "Microsoft.VSTS.Scheduling.StoryPoints")).toBeUndefined();
    expect(field(ops, "System.Description")).toContain("Acceptance criteria");
    expect(warn).toHaveBeenCalledTimes(2);
  });

  it("reuses an existing Feature found by WIQL, else creates one", async () => {
    let found = true;
    const { calls } = mockFetch([
      [
        /POST .*\/_apis\/wit\/wiql/,
        () => ({ json: { workItems: found ? [{ id: 100 }] : [] } }),
      ],
      [/POST .*workitems\/\$Feature/, { json: { id: 101 } }],
    ]);
    const client = new AzdoClient(settings, { log: silentLog });
    const feature = {
      id: "FEAT-01",
      name: "Authentication",
      description: "Sign <in>",
      useCaseIds: [],
    };
    expect(await client.ensureParent(feature)).toMatchObject({
      action: "skipped",
      ref: { key: "100" },
    });
    found = false;
    expect(await client.ensureParent(feature)).toMatchObject({
      action: "created",
      ref: { key: "101" },
    });
    expect((calls[0].body as { query: string }).query).toContain(
      "[System.WorkItemType] = 'Feature'",
    );
    const ops = calls.at(-1)!.body as JsonPatchOp[];
    expect(field(ops, "System.Description")).toContain("Sign &lt;in&gt;");
  });

  it("adds predecessor links, skipping ones that exist", async () => {
    const { calls } = mockFetch([
      [
        /GET .*\/workitems\/4711\?\$expand=relations/,
        {
          json: {
            id: 4711,
            relations: [
              {
                rel: PREDECESSOR_REL,
                url: "https://dev.azure.com/acme/0f3a/_apis/wit/workItems/1",
              },
            ],
          },
        },
      ],
      [/PATCH .*\/workitems\/4711/, { json: { id: 4711 } }],
    ]);
    const client = new AzdoClient(settings, { log: silentLog });
    const out = await client.linkDependencies({
      content: sampleContent(),
      options,
      ref: { key: "4711", url: "x" },
      preExisting: true,
      dependencies: [
        { useCaseId: "UC-001", ref: { key: "1", url: "a" } },
        { useCaseId: "UC-002", ref: { key: "2", url: "b" } },
      ],
    });
    expect(out.every((o) => o.ok)).toBe(true);
    const patches = calls.filter((c) => c.method === "PATCH");
    expect(patches).toHaveLength(1);
    expect((patches[0].body as JsonPatchOp[])[0].value).toEqual({
      rel: PREDECESSOR_REL,
      url: "https://dev.azure.com/acme/_apis/wit/workItems/2",
      attributes: { comment: "UC-003 depends on UC-002 (Coherence)" },
    });
  });
});

describe("testAzdo", () => {
  it("checks the project and work item types", async () => {
    mockFetch([
      [/_apis\/projects\/Acme%20Portal/, { json: { name: "Acme Portal" } }],
      [/workitemtypes\/User%20Story/, { json: { name: "User Story" } }],
      [
        /workitemtypes\/Feature/,
        { status: 404, json: { message: "not found" } },
      ],
    ]);
    const r = await testAzdo(settings);
    expect(r.ok).toBe(false);
    expect(r.message).toContain('has no work item type "Feature"');
  });

  it("reports an HTML sign-in page as a credentials problem", async () => {
    mockFetch([
      [
        /_apis\/projects/,
        {
          status: 203,
          text: "<!DOCTYPE html><html>Sign in</html>",
          headers: { "content-type": "text/html; charset=utf-8" },
        },
      ],
    ]);
    const r = await testAzdo(settings);
    expect(r.ok).toBe(false);
    expect(r.message).toContain("credentials were not accepted");
  });
});
