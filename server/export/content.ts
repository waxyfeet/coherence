const SCENARIO_LABEL: Record<ScenarioType, string> = {
  happy: "happy path",
  alternate: "alternate",
  negative: "negative",
  edge: "edge case",
};

export function elementTypeLabel(
  type: ElementType | "screen" | "general",
): string {
  const words = type.replace(/_/g, " ");
  return `${words.charAt(0).toUpperCase()}${words.slice(1)}`;
}

export function ruleHeading(rule: BusinessRule): string {
  return `${rule.id} · ${rule.element} — ${elementTypeLabel(rule.elementType)}`;
}

export function scenarioHeading(sc: BddScenario): string {
  return `${sc.id} · ${sc.title} (${SCENARIO_LABEL[sc.type] ?? sc.type})`;
}

/** GIVEN / AND … / WHEN / AND … / THEN (every then line) — the product owner's template. */
export function scenarioLines(sc: BddScenario): string[] {
  return [
    ...sc.given.map((g, i) => `${i === 0 ? "GIVEN" : "AND"} ${g}`),
    ...sc.when.map((w, i) => `${i === 0 ? "WHEN" : "AND"} ${w}`),
    ...sc.then.map((t) => `THEN ${t}`),
  ];
}

function fence(lines: string[], lang = "gherkin"): string {
  const body = lines.join("\n");
  const ticks = body.includes("```") ? "````" : "```";
  return `${ticks}${lang}\n${body}\n${ticks}`;
}

/**
 * Reviewed text as literal Markdown: characters Markdown would turn into formatting are escaped, so a rule such as
 * "2*3*4" or "__init__" reaches the tracker exactly as written. Notes are left alone (they may hold formatting).
 */
export function literal(text: string): string {
  return text
    .replace(/[\\`*_[\]~]/g, (c) => `\\${c}`)
    .replace(/^(\s*)([#>])/gm, "$1\\$2");
}

/** Undo literal(): the visible text the BA wrote, for comparisons that must not depend on escaping. */
export function unliteral(markdown: string): string {
  return markdown.replace(/\\([\\`*_[\]~#>])/g, "$1");
}

function bullets(items: string[]): string {
  return items.length
    ? items.map((i) => `- ${literal(i)}`).join("\n")
    : "- None";
}

type DescribedContent = Pick<
  ExportContent,
  "useCase" | "featureName" | "personaName" | "screenNames"
>;

export function buildScenariosMarkdown(uc: UseCase, headingLevel = 4): string {
  if (!uc.scenarios.length) return "- None";
  const hashes = "#".repeat(headingLevel);
  return uc.scenarios
    .map(
      (sc) =>
        `${hashes} ${literal(scenarioHeading(sc))}\n\n${fence(scenarioLines(sc))}`,
    )
    .join("\n\n");
}

/**
 * One markdown document per use case: story, scope, context, pre/postconditions, business rules,
 * (acceptance criteria), assumptions, open questions, notes, footer.
 */
export function buildDescriptionMarkdown(
  content: DescribedContent,
  opts: { includeScenarios: boolean; includeFooter: boolean },
): string {
  const uc = content.useCase;
  const parts: string[] = [];
  parts.push(
    [
      `**As a** ${literal(uc.story.asA)}  `,
      `**I want to** ${literal(uc.story.iWant)}  `,
      `**So that** ${literal(uc.story.soThat)}`,
    ].join("\n"),
  );
  if (uc.scope.trim()) parts.push(`**Scope:** ${literal(uc.scope.trim())}`);

  const context = [
    content.featureName && `**Feature:** ${literal(content.featureName)}`,
    content.personaName && `**Persona:** ${literal(content.personaName)}`,
    content.screenNames.length &&
      `**Screens:** ${literal(content.screenNames.join(", "))}`,
    `**Size:** ${uc.size}`,
    uc.dependsOn.length && `**Depends on:** ${uc.dependsOn.join(", ")}`,
  ].filter(Boolean);
  parts.push(context.join(" · "));

  parts.push(`## Preconditions\n\n${bullets(uc.preconditions)}`);
  parts.push(`## Postconditions\n\n${bullets(uc.postconditions)}`);

  const rules = uc.businessRules.map((r) => {
    const lines = [`### ${literal(ruleHeading(r))}`];
    if (
      r.elementId &&
      r.elementType !== "screen" &&
      r.elementType !== "general"
    )
      lines.push(`\`${r.elementId}\``);
    if (r.description.trim()) lines.push(literal(r.description.trim()));
    if (r.rules.length)
      lines.push(r.rules.map((x) => `- ${literal(x)}`).join("\n"));
    return lines.join("\n\n");
  });
  parts.push(
    `## Business rules\n\n${rules.length ? rules.join("\n\n") : "- None"}`,
  );

  if (opts.includeScenarios)
    parts.push(`## Acceptance criteria\n\n${buildScenariosMarkdown(uc, 4)}`);

  parts.push(`## Assumptions\n\n${bullets(uc.assumptions)}`);
  parts.push(`## Open questions\n\n${bullets(uc.openQuestions)}`);
  if (uc.notes.trim()) parts.push(`## Notes\n\n${uc.notes.trim()}`);
  if (opts.includeFooter) parts.push(`---\n\n${footerLine(uc)}`);
  return parts.join("\n\n");
}

/** Labels: no spaces (Jira rejects them), de-duplicated case-insensitively, order kept. */
export function uniqueLabels(
  labels: string[],
  replaceSpaces: boolean,
): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const raw of labels) {
    const label = replaceSpaces ? raw.trim().replace(/\s+/g, "-") : raw.trim();
    if (!label || seen.has(label.toLowerCase())) continue;
    seen.add(label.toLowerCase());
    out.push(label);
  }
  return out;
}
