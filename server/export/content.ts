import { readOwnedFile } from "../storage/fsUtils";
/**
 * Export content model: what a use case looks like when it leaves Coherence.
 * Content comes from the BA-reviewed .md file (parsed with the project's OutputFormat); when the file is
 * missing or unparseable the model's copy is used and a warning is recorded.
 * The description builders produce one markdown document per use case that the Jira (wiki) and
 * Azure DevOps (HTML) converters turn into their own markup.
 */
import fs from "node:fs/promises";
import type {
  BddScenario,
  BusinessRule,
  ElementType,
  ExternalSystem,
  Project,
  ScenarioType,
  SolutionModel,
  UseCase,
} from "@shared/types";
import { errorMessage } from "../errors";
import type { OutputFormat } from "../formats/types";
import { resolveSpecPath } from "../specs/specStore";
import { stripFrontMatter } from "./markdown";

export interface ExportContent {
  /** Model use case overlaid with the content/structure parsed from its .md file. */
  useCase: UseCase;
  /** Markdown body of the spec file without front matter (rendered from the model when the file is unusable). */
  markdownBody: string;
  source: "file" | "model";
  warnings: string[];
  featureName: string;
  personaName: string;
  screenNames: string[];
}

export const MAX_TITLE_LENGTH = 255;

/** "[UC-003] Sign in with email and password" (trimmed to the trackers' 255-char limit). */
export function exportTitle(uc: Pick<UseCase, "id" | "title">): string {
  return truncate(`[${uc.id}] ${uc.title.trim()}`, MAX_TITLE_LENGTH);
}

export function truncate(text: string, max: number, suffix = "…"): string {
  return text.length <= max
    ? text
    : `${text.slice(0, Math.max(0, max - suffix.length)).trimEnd()}${suffix}`;
}

export function footerLine(uc: Pick<UseCase, "id" | "revision">): string {
  return `_Generated by Coherence — ${uc.id} rev ${uc.revision}_`;
}

/** Existing link for this tracker on the use case, if it was exported before. */
export function existingLink(uc: UseCase, system: ExternalSystem) {
  return uc.external.find((l) => l.system === system);
}

export function displayNames(
  project: Project,
  model: SolutionModel,
  uc: UseCase,
) {
  const featureName =
    model.features.find((f) => f.id === uc.featureId)?.name ?? "";
  const personaName =
    model.personas.find((p) => p.id === uc.personaId)?.name ??
    uc.story.asA ??
    "";
  const screenNames = uc.screenIds.map(
    (id) =>
      project.screens.find((s) => s.id === id)?.name ??
      model.screens.find((a) => a.screenId === id)?.title ??
      id,
  );
  return { featureName, personaName, screenNames };
}

/**
 * Read the reviewed .md for a use case. Falls back to the model (with a warning) when the file is
 * missing, unreadable, unparseable or belongs to another id.
 */
export async function loadExportContent(
  project: Project,
  model: SolutionModel,
  uc: UseCase,
  format: OutputFormat,
): Promise<ExportContent> {
  const warnings: string[] = [];
  let relPath = uc.filePath ?? "";
  try {
    relPath = uc.filePath ?? format.useCasePath(uc);
  } catch {
    // keep whatever we have; reading below will fail and fall back
  }

  let raw: string | undefined;
  if (relPath) {
    try {
      raw = (await readOwnedFile(resolveSpecPath(project, relPath))).toString(
        "utf8",
      );
    } catch (err) {
      const code = (err as NodeJS.ErrnoException)?.code;
      warnings.push(
        code === "ENOENT"
          ? `${uc.id}: the spec file ${relPath} was not found — exported the version stored in the project model.`
          : `${uc.id}: could not read ${relPath} (${errorMessage(err)}) — exported the version stored in the project model.`,
      );
    }
  } else {
    warnings.push(
      `${uc.id}: no spec file is recorded for this use case — exported the version stored in the project model.`,
    );
  }

  let merged = uc;
  let body: string | undefined;
  let source: ExportContent["source"] = "model";
  if (raw !== undefined) {
    try {
      const parsed = format.parseUseCase(raw);
      if (parsed.errors.length) {
        warnings.push(
          `${uc.id}: ${relPath} could not be read as a use case (${parsed.errors.join("; ")}) — exported the version stored in the project model.`,
        );
      } else if (parsed.useCase.id !== uc.id) {
        warnings.push(
          `${uc.id}: ${relPath} belongs to ${parsed.useCase.id} — exported the version stored in the project model.`,
        );
      } else {
        merged = mergeParsedUseCase(uc, parsed.useCase, model);
        body = stripFrontMatter(raw);
        source = "file";
        for (const w of parsed.warnings) warnings.push(`${uc.id}: ${w}`);
      }
    } catch (err) {
      warnings.push(
        `${uc.id}: ${relPath} could not be parsed (${errorMessage(err)}) — exported the version stored in the project model.`,
      );
    }
  }

  const names = displayNames(project, model, merged);
  if (body === undefined) {
    try {
      body = stripFrontMatter(
        format.renderUseCase(merged, {
          project,
          model,
          embedScreenImages: false,
        }),
      );
    } catch {
      body = `# ${merged.id} · ${merged.title}\n\n${buildDescriptionMarkdown({ useCase: merged, ...names }, { includeScenarios: true, includeFooter: false })}`;
    }
  }
  return { useCase: merged, markdownBody: body, source, warnings, ...names };
}

/** Content and structure from the file win; ids/links/paths stay with the model. */
export function mergeParsedUseCase(
  uc: UseCase,
  parsed: Partial<UseCase> & { id: string },
  model: SolutionModel,
): UseCase {
  const known = new Set(model.useCases.map((u) => u.id));
  const pick = <K extends keyof UseCase>(key: K): UseCase[K] =>
    parsed[key] !== undefined ? (parsed[key] as UseCase[K]) : uc[key];
  return {
    ...uc,
    title: pick("title") || uc.title,
    featureId: pick("featureId") || uc.featureId,
    personaId: pick("personaId") || uc.personaId,
    screenIds: pick("screenIds"),
    elementIds: pick("elementIds"),
    dependsOn: (parsed.dependsOn ?? uc.dependsOn).filter(
      (id) => id !== uc.id && known.has(id),
    ),
    size: pick("size"),
    scope: pick("scope"),
    story: pick("story"),
    preconditions: pick("preconditions"),
    postconditions: pick("postconditions"),
    businessRules: pick("businessRules"),
    scenarios: pick("scenarios"),
    assumptions: pick("assumptions"),
    openQuestions: pick("openQuestions"),
    notes: pick("notes"),
    status: pick("status"),
    revision: Math.max(uc.revision, parsed.revision ?? 0),
    external: uc.external.length ? uc.external : (parsed.external ?? []),
  };
}

