import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import type { GitHubSettings } from "@shared/types";
import {
  buildGitHubBody,
  buildGitHubLabels,
  dependsOnLine,
  GitHubClient,
  githubWebBase,
  mergeGitHubLabels,
  previewGitHub,
  testGitHub,
} from "./github";
import { httpDefaults } from "./http";
import { mockFetch, sampleContent, silentLog } from "./testUtils";

const settings: GitHubSettings = {
  owner: "acme",
  repo: "portal",
  token: "ghp_x",
  labels: ["spec"],
  apiBaseUrl: "https://api.github.com",
  useMilestonesForFeatures: true,
};
const options = {
  createFeatureParents: true,
  linkDependencies: true,
  updateExisting: true,
  includeStoryPoints: true,
};

beforeEach(() => {
  httpDefaults.baseDelayMs = 0;
});
afterEach(() => {
  vi.unstubAllGlobals();
  httpDefaults.baseDelayMs = 800;
});

describe("GitHub payloads", () => {
  it("builds the body from the spec markdown without H1, local links or images", () => {
    const body = buildGitHubBody(sampleContent());
    expect(body.startsWith("| Feature | Persona |")).toBe(true);
    expect(body).toContain(
      "| Authentication | Registered user | Login | M | UC-001 |",
    );
    expect(body).toContain("_(screen image: Login — see spec repo)_");
    expect(body).toContain("```gherkin\nGIVEN the Login screen is displayed");
    expect(body).not.toContain("# UC-003 ·");
    expect(
      body.endsWith("---\n\n_Generated by Coherence — UC-003 rev 2_"),
    ).toBe(true);
  });

  it("puts the depends-on line first", () => {
    const line = dependsOnLine([
      { useCaseId: "UC-001", ref: { key: "#12", url: "x" } },
      { useCaseId: "UC-002", ref: { key: "#15", url: "y" } },
    ]);
    expect(line).toBe("**Depends on:** #12 (UC-001), #15 (UC-002)");
    expect(
      buildGitHubBody(sampleContent(), line).startsWith(`${line}\n\n| Feature`),
    ).toBe(true);
  });

  it("builds and merges labels", () => {
    expect(
      buildGitHubLabels(settings, sampleContent(), {
        includeStoryPoints: true,
        featureLabel: "feature: Authentication",
      }),
    ).toEqual(["spec", "coherence", "size: M", "feature: Authentication"]);
    expect(
      mergeGitHubLabels(
        ["bug", "size: S", "feature: Old", "Spec"],
        ["spec", "size: M", "feature: New"],
      ),
    ).toEqual(["bug", "spec", "size: M", "feature: New"]);
  });

  it("derives the web URL for github.com and GHE", () => {
    expect(githubWebBase("https://api.github.com")).toBe("https://github.com");
    expect(githubWebBase("https://ghe.example.com/api/v3")).toBe(
      "https://ghe.example.com",
    );
  });

  it("previews markdown", () => {
    const p = previewGitHub(sampleContent(), settings);
    expect(p.bodyFormat).toBe("markdown");
    expect(p.fields.Feature).toContain('milestone "Authentication"');
  });
});

describe("GitHubClient", () => {
  it("creates an issue with labels and milestone and the API version header", async () => {
    const { calls } = mockFetch([
      [
        /POST .*\/repos\/acme\/portal\/issues$/,
        {
          status: 201,
          json: {
            number: 42,
            html_url: "https://github.com/acme/portal/issues/42",
          },
        },
      ],
    ]);
    const client = new GitHubClient(settings, { log: silentLog });
    const r = await client.upsert({
      content: sampleContent(),
      options,
      parent: { key: "3", url: "m" },
    });
    expect(r).toEqual({
      action: "created",
      ref: { key: "#42", url: "https://github.com/acme/portal/issues/42" },
    });
    expect(calls[0].headers["X-GitHub-Api-Version"]).toBe("2022-11-28");
    expect(calls[0].headers.Authorization).toBe("Bearer ghp_x");
    expect(calls[0].body).toMatchObject({
      title: "[UC-003] Sign in with email and password",
      milestone: 3,
      labels: ["spec", "coherence", "size: M"],
    });
  });

  it("updates an existing issue keeping labels added on GitHub", async () => {
    const { calls } = mockFetch([
      [
        /GET .*\/issues\/42$/,
        {
          json: {
            number: 42,
            html_url: "h",
            // "screenscribe": the label of an issue exported before the rename, kept like any other.
            labels: [
              { name: "bug" },
              { name: "screenscribe" },
              { name: "size: L" },
            ],
          },
        },
      ],
      [/PATCH .*\/issues\/42$/, { json: { number: 42, html_url: "h" } }],
    ]);
    const client = new GitHubClient(settings, { log: silentLog });
    const r = await client.upsert({
      content: sampleContent(),
      options,
      existing: {
        system: "github",
        key: "#42",
        url: "h",
        revision: 1,
        exportedAt: "x",
      },
    });
    expect(r.action).toBe("updated");
    expect((calls[1].body as { labels: string[] }).labels).toEqual([
      "bug",
      "screenscribe",
      "spec",
      "coherence",
      "size: M",
    ]);
  });

  it("recreates a deleted issue (410)", async () => {
    const { calls } = mockFetch([
      [
        /GET .*\/issues\/42$/,
        { status: 410, json: { message: "This issue was deleted" } },
      ],
      [
        /POST .*\/issues$/,
        { status: 201, json: { number: 50, html_url: "h50" } },
      ],
    ]);
    const client = new GitHubClient(settings, { log: silentLog });
    const r = await client.upsert({
      content: sampleContent(),
      options,
      existing: {
        system: "github",
        key: "#42",
        url: "h",
        revision: 1,
        exportedAt: "x",
      },
    });
    expect(r).toEqual({ action: "created", ref: { key: "#50", url: "h50" } });
    expect(calls.map((c) => c.method)).toEqual(["GET", "POST"]);
  });

  it("reuses or creates milestones", async () => {
    const { calls } = mockFetch([
      [
        /GET .*\/milestones\?state=all/,
        { json: [{ number: 3, title: "Authentication", html_url: "m3" }] },
      ],
      [
        /POST .*\/milestones$/,
        { status: 201, json: { number: 4, title: "Orders", html_url: "m4" } },
      ],
    ]);
    const client = new GitHubClient(settings, { log: silentLog });
    expect(
      await client.ensureParent({
        id: "FEAT-01",
        name: "authentication",
        description: "",
        useCaseIds: [],
      }),
    ).toEqual({ action: "skipped", ref: { key: "3", url: "m3" } });
    expect(
      await client.ensureParent({
        id: "FEAT-02",
        name: "Orders",
        description: "Ordering",
        useCaseIds: [],
      }),
    ).toEqual({ action: "created", ref: { key: "4", url: "m4" } });
    expect(calls.filter((c) => c.method === "GET")).toHaveLength(1);
  });

  it('uses "feature:" labels when milestones are off', async () => {
    const { calls } = mockFetch([
      [
        /POST .*\/labels$/,
        {
          status: 422,
          json: {
            message: "Validation Failed",
            errors: [
              { resource: "Label", code: "already_exists", field: "name" },
            ],
          },
        },
      ],
    ]);
    const client = new GitHubClient(
      { ...settings, useMilestonesForFeatures: false },
      { log: silentLog },
    );
    const r = await client.ensureParent({
      id: "FEAT-01",
      name: "Authentication",
      description: "",
      useCaseIds: [],
    });
    expect(r).toEqual({
      action: "skipped",
      ref: {
        key: "feature: Authentication",
        url: "https://github.com/acme/portal/labels/feature%3A%20Authentication",
      },
    });
    expect((calls[0].body as { name: string }).name).toBe(
      "feature: Authentication",
    );
  });

  it("writes the depends-on line in the link pass", async () => {
    const { calls } = mockFetch([
      [/PATCH .*\/issues\/42$/, { json: { number: 42 } }],
    ]);
    const client = new GitHubClient(settings, { log: silentLog });
    const out = await client.linkDependencies({
      content: sampleContent(),
      options,
      ref: { key: "#42", url: "h" },
      preExisting: false,
      dependencies: [{ useCaseId: "UC-001", ref: { key: "#12", url: "x" } }],
    });
    expect(out).toEqual([{ toUseCaseId: "UC-001", ok: true }]);
    expect(
      (calls[0].body as { body: string }).body.startsWith(
        "**Depends on:** #12 (UC-001)\n\n",
      ),
    ).toBe(true);
  });

  it("reports GitHub validation errors readably", async () => {
    mockFetch([
      [
        /POST/,
        {
          status: 422,
          json: {
            message: "Validation Failed",
            errors: [
              { resource: "Issue", field: "milestone", code: "invalid" },
            ],
          },
        },
      ],
    ]);
    const client = new GitHubClient(settings, { log: silentLog });
    await expect(
      client.upsert({
        content: sampleContent(),
        options,
        parent: { key: "99", url: "x" },
      }),
    ).rejects.toThrow("GitHub returned HTTP 422 Unprocessable Entity.");
  });
});

describe("testGitHub", () => {
  it("confirms repository access", async () => {
    mockFetch([
      [
        /GET .*\/repos\/acme\/portal$/,
        {
          json: {
            full_name: "acme/portal",
            has_issues: true,
            permissions: { push: true },
          },
        },
      ],
    ]);
    expect(await testGitHub(settings)).toMatchObject({
      ok: true,
      message: "Connected to GitHub repository acme/portal.",
    });
  });

  it("explains a missing repository and disabled issues", async () => {
    mockFetch([[/GET/, { status: 404, json: { message: "Not Found" } }]]);
    expect((await testGitHub(settings)).message).toBe(
      "Repository acme/portal was not found, or the token cannot access it.",
    );
    mockFetch([
      [/GET/, { json: { full_name: "acme/portal", has_issues: false } }],
    ]);
    expect(await testGitHub(settings)).toMatchObject({ ok: false });
  });
});
