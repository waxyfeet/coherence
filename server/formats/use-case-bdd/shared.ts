/**
 * OWNER: formats builder.
 * Bits shared by the support-file renderers (links, status labels, the generated-file marker).
 */
import type { UseCase, UseCaseStatus } from "@shared/types";
import { escapeCell, mdLink, oneLine } from "../markdown";
import { relativeLink, type Lookup } from "./lookup";
import { STATUS_LABEL } from "./vocabulary";

/**
 * Marker placed at the top of every derived file. The spec store only ever deletes derived files that
 * carry it, so files a BA adds to the folder are never removed.
 */
export const GENERATED_MARKER = "Generated by Coherence";
/** The marker before the visible rename (owner decision, installer Stage 7): those files are still Coherence's own. */
export const LEGACY_GENERATED_MARKER = "Generated by ScreenScribe";

export function generatedMarker(): string {
  return `<!-- ${GENERATED_MARKER}: this file is rewritten every time the specs are written — edit the use case files in use-cases/ instead. -->`;
}

/** True when a file's first lines carry the generated-file marker (either name). */
export function isGeneratedContent(content: string): boolean {
  const head = content.slice(0, 400);
  return (
    head.includes(GENERATED_MARKER) || head.includes(LEGACY_GENERATED_MARKER)
  );
}

/** [UC-003](use-cases/UC-003-x.md) relative to `fromFile`. */
export function ucLink(lookup: Lookup, uc: UseCase, fromFile: string): string {
  return mdLink(uc.id, relativeLink(fromFile, lookup.useCaseFile(uc)));
}

/** [UC-003 · Title](use-cases/UC-003-x.md) relative to `fromFile`. */
export function ucLinkLabel(
  lookup: Lookup,
  uc: UseCase,
  fromFile: string,
): string {
  const title = oneLine(uc.title);
  return mdLink(
    title ? `${uc.id} · ${title}` : uc.id,
    relativeLink(fromFile, lookup.useCaseFile(uc)),
  );
}

/** Links for a list of use case ids (unknown ids rendered as plain text). */
export function ucLinks(
  lookup: Lookup,
  ids: string[],
  fromFile: string,
): string {
  return ids
    .map((id) => {
      const uc = lookup.useCases.get(id);
      return uc ? ucLink(lookup, uc, fromFile) : escapeCell(id);
    })
    .join(", ");
}

export function statusLabel(status: UseCaseStatus): string {
  return STATUS_LABEL[status] ?? status;
}

/** "features/UC-003-sign-in.feature" for a use case file "use-cases/UC-003-sign-in.md". */
export function featureFilePath(useCaseFile: string): string {
  const base = useCaseFile.split("/").pop() ?? useCaseFile;
  return `features/${base.replace(/\.md$/i, "")}.feature`;
}
